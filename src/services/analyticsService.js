/**
 * Export analytics data as PDF
 * @param {string} restaurantId - Restaurant ID to export analytics for
 * @returns {Promise<string>} Path to the downloaded PDF file
 */
export const exportAnalyticsPDF = async (restaurantId) => {
  try {
    const response = await api.get(`/owner/analytics/export?restaurantId=${restaurantId}`);

    // Handle JSON response (new format)
    if (response.data?.ok && response.data?.data) {
      const htmlContent = generateAnalyticsHTML(response.data.data);

      // Try to use react-native-html-to-pdf if available
      try {
        const RNHTMLtoPDF = require('react-native-html-to-pdf').default;
        const options = {
          html: htmlContent,
          fileName: `analytics-${restaurantId}-${Date.now()}`,
          directory: 'Documents',
        };
        const file = await RNHTMLtoPDF.convert(options);
        return file.filePath;
      } catch (pdfError) {
        // Fallback: save as HTML file
        const timestamp = Date.now();
        const fileName = `analytics-${restaurantId}-${timestamp}.html`;
        const path = `${RNFS.DocumentDirectoryPath}/${fileName}`;
        await RNFS.writeFile(path, htmlContent, 'utf8');
        return path;
      }
    }

    // Handle blob response (legacy format)
    const timestamp = Date.now();
    const fileName = `analytics-${restaurantId}-${timestamp}.pdf`;
    const path = `${RNFS.DocumentDirectoryPath}/${fileName}`;

    let base64Data = response.data;
    if (typeof base64Data !== 'string') {
      base64Data = await blobToBase64(response.data);
    }

    await RNFS.writeFile(path, base64Data, 'base64');
    return path;
  } catch (error) {
    console.error('Export analytics PDF error:', error);
    throw new Error('Failed to export analytics report');
  }
};

