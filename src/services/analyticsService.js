/**
 * Open PDF or HTML file with default viewer
 * @param {string} filePath - Path to the file
 */
export const openPDF = async (filePath) => {
  try {
    await FileViewer.open(filePath, {
      showOpenWithDialog: true,
      showAppsSuggestions: true,
    });
  } catch (error) {
    console.error('Open file error:', error);
    Alert.alert(
      'Cannot Open File',
      'Please install a PDF or HTML viewer app to open this file.',
      [{ text: 'OK' }]
    );
  }
};

/**
 * Share PDF file using native share dialog
 * @param {string} filePath - Path to the PDF file
 */
export const sharePDF = async (filePath) => {
  try {
    const { Share } = require('react-native');

    await Share.share({
      url: Platform.OS === 'ios' ? filePath : `file://${filePath}`,
      title: 'Share Report',
    });
  } catch (error) {
    console.error('Share file error:', error);
    throw new Error('Failed to share file');
  }
};

/**
 * Convert blob to base64 string
 * @param {Blob} blob - Blob data
 * @returns {Promise<string>} Base64 encoded string
 */
const blobToBase64 = (blob) => {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = reject;
    reader.onload = () => {
      const dataUrl = reader.result;
      const base64 = dataUrl.split(',')[1];
      resolve(base64);
    };
    reader.readAsDataURL(blob);
  });
};

/**
 * Delete file from device
 * @param {string} filePath - Path to the file
 */
export const deletePDF = async (filePath) => {
  try {
    const exists = await RNFS.exists(filePath);
    if (exists) {
      await RNFS.unlink(filePath);
    }
  } catch (error) {
    console.error('Delete file error:', error);
  }
};

/**
 * Get list of all exported files
 * @returns {Promise<Array>} List of exported files
 */
export const listExportedPDFs = async () => {
  try {
    const files = await RNFS.readDir(RNFS.DocumentDirectoryPath);
    return files.filter(file =>
      file.name.endsWith('.pdf') || file.name.endsWith('.html')
    );
  } catch (error) {
    console.error('List files error:', error);
    return [];
  }
};
